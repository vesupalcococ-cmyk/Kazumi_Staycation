    private LocalTime parseTime(String time, String amPm) {
        DateTimeFormatter formatter =
                DateTimeFormatter.ofPattern("h:mm a", java.util.Locale.ENGLISH);

        return LocalTime.parse(
                time.trim() + " " + amPm.trim(),
                formatter
        );
    }
    
