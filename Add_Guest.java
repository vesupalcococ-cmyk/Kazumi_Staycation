    private void AddGuestActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddGuestActionPerformed
    String nameValue = fullname.getText().trim();
    String emailValue = email.getText().trim();
        if (!emailValue.matches("^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$")) {
        JOptionPane.showMessageDialog(this,
                "Please enter a valid email address.",
                "Invalid Email",
                JOptionPane.ERROR_MESSAGE);
        email.requestFocus();
        return;
    }
    String contactValue = contactnumber.getText().trim();
            if (!contactValue.matches("09[0-9]{9}")) {
        JOptionPane.showMessageDialog(this,
                "Contact number must contain exactly 11 digits and start with 09.",
                "Invalid Contact Number",
                JOptionPane.ERROR_MESSAGE);
        contactnumber.requestFocus();
        return;
    }
            
            if (!booked.isSelected() && !reserved.isSelected()) {
            JOptionPane.showMessageDialog(this,
                    "Please select RESERVED or BOOKED.",
                    "Select Status",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }
        String bookingType = booked.isSelected() ? "Booked" : "Reservation";


    
    
    try {
        LocalTime parsedTimeIn = parseTime(
                timein.getText(),
                jComboBox1.getSelectedItem().toString()
        );

        LocalTime parsedTimeOut = parseTime(
                timeout.getText(),
                jComboBox2.getSelectedItem().toString()
        );

    } catch (DateTimeParseException | NullPointerException ex) {
        JOptionPane.showMessageDialog(this,
                "Please enter valid times, such as 2:30, and select AM or PM.",
                "Invalid Time",
                JOptionPane.ERROR_MESSAGE);
        return;
    }

    
        DateTimeFormatter formatter =
        DateTimeFormatter.ofPattern("yyyy-MM-dd");

        LocalDate checkIn;
        LocalDate checkOut;

        try {
            checkIn = LocalDate.parse(
                    checkindate.getText().trim(), formatter);

            checkOut = LocalDate.parse(
                    checkoutdate.getText().trim(), formatter);

        } catch (DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this,
                    "Please select both check-in and check-out dates.",
                    "Missing Dates",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (checkIn.isBefore(LocalDate.now())) {
            JOptionPane.showMessageDialog(this,
                    "Check-in can't be in the past.",
                    "Invalid Dates",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!checkOut.isAfter(checkIn)) {
            JOptionPane.showMessageDialog(this,
                    "Check-out must be after check-in.",
                    "Invalid Dates",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        try (Connection conn = DBConnection.connect()) {
            
             // 1. Check whether the selected dates are available
            String checkSql = "SELECT COUNT(*) FROM tbl_guest WHERE check_in < ? AND check_out > ?";
            try (PreparedStatement p = conn.prepareStatement(checkSql)) {
                p.setDate(1, java.sql.Date.valueOf(checkOut));
                p.setDate(2, java.sql.Date.valueOf(checkIn));
                try (ResultSet rs = p.executeQuery()) {
                    rs.next();
                    if (rs.getInt(1) > 0) {
                        JOptionPane.showMessageDialog(this,
                            "Those dates overlap an existing booking. Check the Availability page.",
                            "Not available", JOptionPane.ERROR_MESSAGE);
                        return;
                    }
                }
            }


            // 3. Save the booking using the generated address_id
            // Save the booking without address information
String bookingSql =
    "INSERT INTO tbl_guest " +
    "(full_name, email, contact, check_in, check_out, booking_type) " +
    "VALUES (?, ?, ?, ?, ?, ?)";

try (PreparedStatement pst = conn.prepareStatement(bookingSql)) {
    pst.setString(1, nameValue);
    pst.setString(2, emailValue);
    pst.setString(3, contactValue);
    pst.setDate(4, java.sql.Date.valueOf(checkIn));
    pst.setDate(5, java.sql.Date.valueOf(checkOut));
    pst.setString(6, bookingType);
    pst.executeUpdate();
}

            JOptionPane.showMessageDialog(this,
                "Guest added successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE);

            // 4. Clear the form
            fullname.setText("");
            email.setText("");
            contactnumber.setText("");
            checkindate.setText("");
            checkoutdate.setText("");
            
            booked.setSelected(false);
            reserved.setSelected(false);
            updateStatusLabel();
            
            // Reset selected date variables
            checkIn = null;
            checkOut = null;

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(),
                "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_AddGuestActionPerformed

