        private void updateCalendar(javax.swing.JLabel monthLabel) {

    String[] days = {"SUN", "MON", "TUE", "WED", "THURS", "FRI", "SAT"};

    javax.swing.table.DefaultTableModel model =
            new javax.swing.table.DefaultTableModel(days, 6) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    int firstColumn = currentMonth.atDay(1).getDayOfWeek().getValue() % 7;
    int totalDays = currentMonth.lengthOfMonth();

    for (int day = 1; day <= totalDays; day++) {
        int cell = firstColumn + day - 1;
        model.setValueAt(String.valueOf(day), cell / 7, cell % 7);
    }

    jTable1.setModel(model);
    jTable1.setRowHeight(35);
    jTable1.setShowGrid(true);
    
    
    // day number -> "BOOKED" or "RESERVED" (days not in the map = no bookings)
    java.util.Map<Integer, String> dayStatus = loadDayStatuses();
        
    jTable1.setDefaultRenderer(Object.class,
            new javax.swing.table.DefaultTableCellRenderer() {

        @Override
        public java.awt.Component getTableCellRendererComponent(
                javax.swing.JTable table, Object value, boolean isSelected,
                boolean hasFocus, int row, int column) {

            java.awt.Component component = super.getTableCellRendererComponent(
                    table, value, isSelected, hasFocus, row, column);

            setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
            setOpaque(true);

            String status = null;
            if (value != null) {
                status = dayStatus.get(Integer.parseInt(value.toString()));
            }

            if ("BOOKED".equals(status)) {
    component.setBackground(new java.awt.Color(225, 139, 161)); // pink
    component.setForeground(java.awt.Color.WHITE);
} else if ("RESERVED".equals(status)) {
    component.setBackground(new java.awt.Color(155, 89, 182));  // purple
    component.setForeground(java.awt.Color.WHITE);
} else if ("COMPLETED".equals(status)) {
    component.setBackground(new java.awt.Color(76, 175, 80));   // green
    component.setForeground(java.awt.Color.WHITE);
} else {
    component.setBackground(java.awt.Color.WHITE);              // no bookings
    component.setForeground(java.awt.Color.BLACK);
}

            return component;
        }
    });

    String monthName = currentMonth.getMonth()
            .getDisplayName(java.time.format.TextStyle.FULL, java.util.Locale.ENGLISH)
            .toUpperCase();

    monthLabel.setText(monthName + " " + currentMonth.getYear());
}

private java.util.Map<Integer, String> loadDayStatuses() {

    java.util.Map<Integer, String> dayStatus = new java.util.HashMap<>();

    String sql = "SELECT check_in, check_out, time_in, time_out, booking_type FROM tbl_guest "
        + "WHERE check_in < ? AND check_out > ?";

    try (
            java.sql.Connection conn = DBConnection.connect();
            java.sql.PreparedStatement pst = conn.prepareStatement(sql)
    ) {

        pst.setDate(1, java.sql.Date.valueOf(currentMonth.plusMonths(1).atDay(1)));
        pst.setDate(2, java.sql.Date.valueOf(currentMonth.atDay(1)));

        try (java.sql.ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {

                java.sql.Date inDate = rs.getDate("check_in");
                java.sql.Date outDate = rs.getDate("check_out");

                if (inDate == null || outDate == null) {
                    continue;
                }

                // same rule as Guest Records
String status;
if (rs.getTime("time_out") != null) {
    status = "COMPLETED";
} else if (rs.getTime("time_in") != null
        || "Booked".equalsIgnoreCase(rs.getString("booking_type"))) {
    status = "BOOKED";
} else {
    status = "RESERVED";
}

                java.time.LocalDate in = inDate.toLocalDate();
                java.time.LocalDate out = outDate.toLocalDate();

                for (java.time.LocalDate date = in;
                        date.isBefore(out);
                        date = date.plusDays(1)) {

                    if (java.time.YearMonth.from(date).equals(currentMonth)) {
                        int d = date.getDayOfMonth();
                        // if both overlap on one day, Booked (pink) wins
                        String existing = dayStatus.get(d);
if (existing == null || priority(status) > priority(existing)) {
    dayStatus.put(d, status);
}
                    }
                }
            }
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Error loading booked dates: " + e.getMessage(),
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
    }

    return dayStatus;
}
private int priority(String status) {
    switch (status) {
        case "BOOKED":   return 3;
        case "RESERVED": return 2;
        default:         return 1; // COMPLETED
    }
}
