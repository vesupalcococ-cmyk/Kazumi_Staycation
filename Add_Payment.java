    private void calculateBalance() {
    try {
        String totalText = grandtotal.getText().trim();
        String downText = downpayment.getText().trim();

        if (totalText.isEmpty() || downText.isEmpty()) {
            balance.setText("[]");
            return;
        }

        java.math.BigDecimal total =
                new java.math.BigDecimal(totalText);

        java.math.BigDecimal down =
                new java.math.BigDecimal(downText);

        java.math.BigDecimal remaining = total.subtract(down);

        balance.setText(remaining.toPlainString());

    } catch (NumberFormatException ex) {
        balance.setText("[]");
    }
}

        private void setupBalanceListener() {
    DocumentListener listener = new DocumentListener() {
        @Override
        public void insertUpdate(DocumentEvent e) {
            calculateBalance();
        }

        @Override
        public void removeUpdate(DocumentEvent e) {
            calculateBalance();
        }

        @Override
        public void changedUpdate(DocumentEvent e) {
            calculateBalance();
        }
    };

    grandtotal.getDocument().addDocumentListener(listener);
    downpayment.getDocument().addDocumentListener(listener);
}
        
        private void setupCalendarListener() {
    // Display the selected calendar date in the text field
    java.text.SimpleDateFormat dateFormat =
            new java.text.SimpleDateFormat("yyyy-MM-dd");

    checkin.setEditable(false);

    // Set the initial date
    checkin.setText(dateFormat.format(jCalendar1.getDate()));

    // Update the text field whenever the calendar date changes
    jCalendar1.addPropertyChangeListener("calendar", evt -> {
        java.util.Date selectedDate = jCalendar1.getDate();

        if (selectedDate != null) {
            checkin.setText(dateFormat.format(selectedDate));
        }
    });
}
    

