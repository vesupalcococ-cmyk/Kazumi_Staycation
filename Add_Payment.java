    private void searchguestnameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchguestnameActionPerformed
        
    String keyword = searchguestname.getText().trim();

    if (keyword.isEmpty()) {
        guestinfos.setText(
                "[ID] [Full Name] [Contact Number] [Email]");
        txtGuestID.setText("");
        return;
    }

    String sql = "SELECT ID, full_name, contact, email "
               + "FROM tbl_guest "
               + "WHERE full_name LIKE ? "
               + "ORDER BY full_name";

    ArrayList<Object[]> guests = new ArrayList<>();

    try (Connection conn = DBConnection.connect();
         PreparedStatement ps = conn.prepareStatement(sql)) {

        ps.setString(1, "%" + keyword + "%");

        try (ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                guests.add(new Object[]{
                    rs.getInt("ID"),
                    rs.getString("full_name"),
                    rs.getString("contact"),
                    rs.getString("email")
                });
            }
        }

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(
                this,
                "Unable to search guest records:\n"
                + ex.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE);
        return;
    }

    if (guests.isEmpty()) {
        guestinfos.setText("No matching guest found.");
        txtGuestID.setText("");

        JOptionPane.showMessageDialog(
                this,
                "No existing guest found with that name.");
        return;
    }

    String[] choices = new String[guests.size()];

    for (int i = 0; i < guests.size(); i++) {
        Object[] g = guests.get(i);

        choices[i] = "ID: " + g[0]
                + " | Name: " + g[1]
                + " | Contact: " + g[2]
                + " | Email: " + g[3];
    }

    Object selected = JOptionPane.showInputDialog(
            this,
            "Select the correct guest using their ID:",
            "Matching Guest Records",
            JOptionPane.QUESTION_MESSAGE,
            null,
            choices,
            choices[0]);

    if (selected == null) {
        txtGuestID.setText("");
        return;
    }

    int selectedIndex = -1;

    for (int i = 0; i < choices.length; i++) {
        if (choices[i].equals(selected)) {
            selectedIndex = i;
            break;
        }
    }

    if (selectedIndex >= 0) {
        Object[] g = guests.get(selectedIndex);

        guestinfos.setText(
                "<html>[ID: " + g[0]
                + "] [Full Name: " + g[1]
                + "] [Contact Number: " + g[2]
                + "] [Email: " + g[3] + "]</html>");

        // Automatically fill ENTER ID NUMBER
        txtGuestID.setText(String.valueOf(g[0]));
    }
    
    
    }//GEN-LAST:event_searchguestnameActionPerformed

    private void addpaymentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addpaymentActionPerformed
            String guestID = txtGuestID.getText().trim();
            String totalText = grandtotal.getText().trim();
            String downText = downpayment.getText().trim();
            String method = paymentmethod.getSelectedItem().toString();
            String reference = referencenumber.getText().trim();
            String time = timeField.getText().trim();
   
    if (guestID.isEmpty() || totalText.isEmpty() || downText.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please complete the Guest ID, Grand Total, and Downpayment.");
        return;
    }

    try {
        int id = Integer.parseInt(guestID);
        java.math.BigDecimal total = new java.math.BigDecimal(totalText);
        java.math.BigDecimal down = new java.math.BigDecimal(downText);

        if (total.compareTo(java.math.BigDecimal.ZERO) <= 0
                || down.compareTo(java.math.BigDecimal.ZERO) < 0
                || down.compareTo(total) > 0) {
            JOptionPane.showMessageDialog(this,
                    "Please check the Grand Total and Downpayment.");
            return;
        }

        if (time.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Please enter the payment time (HH:mm).");
            return;
        }
        
        if (!reference.matches("[0-9]{13}")) {
                JOptionPane.showMessageDialog(this,
                        "Reference number must contain exactly 13 digits.",
                        "Invalid Reference Number",
                        JOptionPane.ERROR_MESSAGE);
                referencenumber.requestFocus();
                return;
            }

        // Get the date selected in the JCalendar.
        java.util.Date selectedDate = jCalendar1.getDate();

        java.sql.Date paymentDate =
                new java.sql.Date(selectedDate.getTime());

        DateTimeFormatter formatter =
        DateTimeFormatter.ofPattern("h:mm a",
                java.util.Locale.ENGLISH);

        LocalTime localTime = LocalTime.parse(
                timeField.getText().trim() + " "
                + ampmComboBox.getSelectedItem().toString(),
                formatter);

        java.sql.Time paymentTime = java.sql.Time.valueOf(localTime);

        java.math.BigDecimal remaining = total.subtract(down);
        balance.setText(String.format("%.2f", remaining));

        // Save payment to MySQL.
        String sql = "INSERT INTO tbl_payment "
                + "(guest_id, grand_total, downpayment, balance, "
                + "payment_method, reference_number, payment_date, payment_time) "
                + "VALUES (?, ?, ?, ?, ?, ?, ?, ?)";

        try (java.sql.Connection conn = DBConnection.connect();
             java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setInt(1, id);
            pst.setBigDecimal(2, total);
            pst.setBigDecimal(3, down);
            pst.setBigDecimal(4, remaining);
            pst.setString(5, method);
            pst.setString(6, reference.isEmpty() ? null : reference);
            pst.setDate(7, paymentDate);
            pst.setTime(8, paymentTime);

            int rows = pst.executeUpdate();

            if (rows > 0) {
                JOptionPane.showMessageDialog(this,
                        "Payment saved successfully!\n\n"
                        + "Guest ID: " + id
                        + "\nGrand Total: " + total
                        + "\nDownpayment: " + down
                        + "\nBalance: " + remaining
                        + "\nPayment Method: " + method);
            }
        }

    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this,
                "Guest ID must be a whole number, and amounts must be valid numbers.");
    } catch (java.time.format.DateTimeParseException ex) {
    JOptionPane.showMessageDialog(this,
            "Invalid time. Please enter the time as H:mm, "
            + "such as 2:30, and select AM or PM.");
    } catch (java.sql.SQLException ex) {
        JOptionPane.showMessageDialog(this,
                "Database error: " + ex.getMessage());
    } catch (NullPointerException ex) {
        JOptionPane.showMessageDialog(this,
                "Please select a payment date.");
    }
    
    

    }//GEN-LAST:event_addpaymentActionPerformed

